/**
 * Build script
 * ─────────────────────────────────────────────────────────────
 * Generates assets/js/env.js from environment variables, so no keys
 * are ever committed to Git.
 *
 *   npm run env     → generate env.js only (local development)
 *   npm run build   → generate env.js + copy the site into dist/ (Vercel)
 *
 * Where the values come from:
 *   - Vercel: Project → Settings → Environment Variables
 *   - Locally: a .env file in the project root (see .env.example)
 *
 * Safety: the build refuses a Supabase SECRET key (service_role / sb_secret_),
 * because everything in env.js is visible in the browser.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BUILD_DIST = process.argv.includes('--dist');
const ON_CI = Boolean(process.env.VERCEL || process.env.CI);

/* ── 1. Load .env (local only; real environment variables take priority) ── */
function loadDotEnv(file) {
  if (!fs.existsSync(file)) return;
  for (const raw of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const match = line.match(/^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
    if (!match) continue;
    let value = match[2].trim();
    if (/^(['"]).*\1$/.test(value)) value = value.slice(1, -1);
    if (process.env[match[1]] === undefined) process.env[match[1]] = value;
  }
}
loadDotEnv(path.join(ROOT, '.env'));

/* ── 2. Validate ── */
const url = (process.env.SUPABASE_URL || '').trim().replace(/\/+$/, '');
const key = (process.env.SUPABASE_ANON_KEY || '').trim();

function isSecretKey(k) {
  if (k.startsWith('sb_secret_')) return true;
  const parts = k.split('.');
  if (parts.length !== 3) return false;
  try {
    return JSON.parse(Buffer.from(parts[1], 'base64url').toString()).role === 'service_role';
  } catch {
    return false;
  }
}

const missing = [];
if (!/^https?:\/\/[^\s/]+$/.test(url)) missing.push('SUPABASE_URL (e.g. https://abcd.supabase.co)');
if (!key) missing.push('SUPABASE_ANON_KEY (the anon / publishable key)');

if (key && isSecretKey(key)) {
  console.error('\n✖ SUPABASE_ANON_KEY is a SECRET key (service_role / sb_secret_).');
  console.error('  It would be exposed in the browser. Use the anon / publishable key instead.\n');
  process.exit(1);
}

if (missing.length) {
  const msg = `Missing environment variables:\n  - ${missing.join('\n  - ')}`;
  if (ON_CI) {
    console.error(`\n✖ ${msg}\n  Add them in Vercel → Settings → Environment Variables, then redeploy.\n`);
    process.exit(1);
  }
  console.warn(`\n⚠ ${msg}\n  Copy .env.example to .env and fill it in. The site will show the setup screen.\n`);
}

/* ── 3. Write assets/js/env.js ── */
const envFile = path.join(ROOT, 'assets/js/env.js');
fs.writeFileSync(envFile,
  '// AUTO-GENERATED by scripts/build.mjs — do not edit and do not commit.\n' +
  `export const ENV = Object.freeze(${JSON.stringify({ SUPABASE_URL: url, SUPABASE_ANON_KEY: key }, null, 2)});\n`);
console.log('✔ assets/js/env.js generated');

/* ── 4. Copy the static site into dist/ (for Vercel) ── */
if (BUILD_DIST) {
  const dist = path.join(ROOT, 'dist');
  fs.rmSync(dist, { recursive: true, force: true });
  fs.mkdirSync(dist);
  for (const item of ['index.html', 'privacy.html', 'assets', 'vendor']) {
    fs.cpSync(path.join(ROOT, item), path.join(dist, item), { recursive: true });
  }
  console.log('✔ site copied to dist/');
}
